create or replace package body pkg_loan_core is

    function fn_calc_monthly_payment(p_principal number, p_rate number, p_months number)
        return number is
    begin
        if p_principal <= 0 or p_months <= 0 then
            raise_application_error(-20301, 'invalid loan input values');
        end if;

        return (p_principal * (p_rate/12)) /
               (1 - power(1+(p_rate/12), -p_months));

    exception
        when zero_divide then
            raise_application_error(-20302, 'division by zero: invalid rate or months');
        when others then
            raise_application_error(-20303, 'unexpected error in fn_calc_monthly_payment');
    end;



    procedure pr_apply_payment(p_loan number, p_amount number) is
    begin
        if p_amount <= 0 then
            raise_application_error(-20310, 'payment amount must be positive');
        end if;

        insert into payment(loan_id, amount, payment_date)
        values (p_loan, p_amount, systimestamp);

        update loan
        set remaining_balance = remaining_balance - p_amount
        where loan_id = p_loan;

    exception
        when no_data_found then
            raise_application_error(-20311, 'loan not found');
        when others then
            raise_application_error(-20399, 'unexpected error in pr_apply_payment');
    end;



    procedure pr_mark_overdue_loans(p_date date) is
        cursor c_loans is
            select loan_id, status
            from loan
            where maturity_date < p_date
              and status = 'Active';

        v_rec c_loans%rowtype;
    begin
        open c_loans;
        loop
            fetch c_loans into v_rec;
            exit when c_loans%notfound;

            update loan
            set status = 'Late'
            where loan_id = v_rec.loan_id;
        end loop;
        close c_loans;

    exception
        when others then
            raise_application_error(-20400, 'error marking overdue loans');
    end;

end pkg_loan_core;
