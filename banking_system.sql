DECLARE
    v_avg_balance          NUMBER := 0;
    v_total_remaining      NUMBER := 0;
    v_has_late_loans       NUMBER := 0;
    v_requested_amount     NUMBER := NVL(:P2_DESIRED_AMOUNT, 0);
    v_term_months          NUMBER := NVL(:P2_TERM_MONTHS, 0);
    v_interest_rate        NUMBER := NVL(:P2_INTEREST_RATE, 0);
    v_score                NUMBER := 0;
    v_status               VARCHAR2(50);
    v_comment              VARCHAR2(4000);
    v_max_recommended      NUMBER := 0;
BEGIN
    SELECT NVL(AVG(CURRENT_BALANCE), 0)
    INTO   v_avg_balance
    FROM   ACCOUNTS
    WHERE  CUSTOMER_ID = :P2_CUSTOMER_ID
      AND  STATUS = 'Active';

    SELECT NVL(SUM(REMAINING_BALANCE), 0)
    INTO   v_total_remaining
    FROM   LOAN
    WHERE  CUSTOMER_ID = :P2_CUSTOMER_ID
      AND  STATUS = 'Active';

    SELECT COUNT(*)
    INTO   v_has_late_loans
    FROM   LOAN
    WHERE  CUSTOMER_ID = :P2_CUSTOMER_ID
      AND  STATUS IN ('Late', 'Defaulted');

    v_score := 0;

    IF v_avg_balance >= 10000 THEN
        v_score := v_score + 40;
    ELSIF v_avg_balance >= 3000 THEN
        v_score := v_score + 30;
    ELSIF v_avg_balance >= 1000 THEN
        v_score := v_score + 20;
    ELSE
        v_score := v_score + 10;
    END IF;

    IF v_total_remaining = 0 THEN
        v_score := v_score + 30;
    ELSIF v_total_remaining < v_avg_balance * 2 THEN
        v_score := v_score + 20;
    ELSE
        v_score := v_score + 5;
    END IF;

    IF v_has_late_loans = 0 THEN
        v_score := v_score + 30;
    ELSE
        v_score := v_score + 5;
    END IF;

    v_max_recommended := GREATEST(v_avg_balance * 3 - v_total_remaining, 0);

    IF v_score >= 70 AND v_requested_amount <= v_max_recommended THEN
        v_status := 'Eligible';
    ELSIF v_score >= 50 AND v_requested_amount <= v_max_recommended * 1.2 THEN
        v_status := 'Borderline';
    ELSE
        v_status := 'Not Eligible';
    END IF;

    v_comment := 'Avg balance: ' || TO_CHAR(v_avg_balance)
              || ', Active loan debt: ' || TO_CHAR(v_total_remaining)
              || ', Late loans: ' || v_has_late_loans;

    :P2_ELIGIBILITY_STATUS    := v_status;
    :P2_MAX_RECOMMENDED       := v_max_recommended;
    :P2_RISK_SCORE            := v_score;
    :P2_COMMENTS              := v_comment;
END;



