create or replace package body pkg_customer_tools is

    procedure pr_get_customer_profile(p_cust number, p_out out t_profile) is
    begin
        select nvl(sum(current_balance),0)
        into p_out.total_balance
        from accounts
        where customer_id = p_cust;

        select nvl(sum(remaining_balance),0)
        into p_out.total_debt
        from loan
        where customer_id = p_cust;

    exception
        when others then
            raise_application_error(-20500, 'error retrieving customer profile');
    end;



    function fn_customer_risk_score(p_cust number) return number is
        v_prof t_profile;
        v_score number := 0;
    begin
        pr_get_customer_profile(p_cust, v_prof);

        if v_prof.total_balance > 5000 then 
            v_score := v_score + 50; 
        end if;

        if v_prof.total_debt < 2000 then 
            v_score := v_score + 50; 
        end if;

        return v_score;

    exception
        when others then
            raise_application_error(-20501, 'error calculating customer risk score');
    end;

end pkg_customer_tools;
