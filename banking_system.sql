    procedure pr_branch_totals(p_date date) is
        v_list t_amount_list;
    begin
        select sum(amount)
        bulk collect into v_list
        from transactions
        where trunc(transaction_date) = trunc(p_date)
        group by branch_id;

        for i in 1 .. v_list.count loop
            dbms_output.put_line('branch total: ' || v_list(i));
        end loop;
    end;

