create or replace package pkg_transaction_core is
    c_deposit  constant number := 1;
    c_withdraw constant number := 2;
    c_transfer constant number := 3;

    procedure pr_deposit(p_acc number, p_amount number);
    procedure pr_withdraw(p_acc number, p_amount number);
    procedure pr_transfer(p_from number, p_to number, p_amount number);

    function fn_account_balance(p_acc number) return number;
end pkg_transaction_core;
/


create or replace package body pkg_transaction_core is

    procedure pr_deposit(p_acc number, p_amount number) is
    begin
        if p_amount <= 0 then
            raise_application_error(-20101, 'deposit amount must be positive');
        end if;

        insert into transactions(transaction_type_id, to_account_id, amount, transaction_date)
        values (c_deposit, p_acc, p_amount, systimestamp);

    exception
        when no_data_found then
            raise_application_error(-20110, 'account not found');
        when others then
            raise_application_error(-20199, 'unexpected error in pr_deposit');
    end;



    procedure pr_withdraw(p_acc number, p_amount number) is
    begin
        if p_amount <= 0 then
            raise_application_error(-20102, 'withdraw amount must be positive');
        end if;

        insert into transactions(transaction_type_id, from_account_id, amount, transaction_date)
        values (c_withdraw, p_acc, p_amount, systimestamp);

    exception
        when others then
            raise_application_error(-20200, 'unexpected error in pr_withdraw');
    end;



    procedure pr_transfer(p_from number, p_to number, p_amount number) is
    begin
        if p_amount <= 0 then
            raise_application_error(-20103, 'transfer amount must be positive');
        end if;

        if p_from = p_to then
            raise_application_error(-20104, 'cannot transfer to same account');
        end if;

        insert into transactions(transaction_type_id, from_account_id, to_account_id, amount, transaction_date)
        values (c_transfer, p_from, p_to, p_amount, systimestamp);

    exception
        when others then
            raise_application_error(-20201, 'unexpected error in pr_transfer');
    end;



    function fn_account_balance(p_acc number) return number is
        v_bal number;
    begin
        select current_balance into v_bal
        from accounts 
        where account_id = p_acc;

        return v_bal;

    exception
        when no_data_found then
            return 0;
        when others then
            raise_application_error(-20202, 'unexpected error in fn_account_balance');
    end;

end pkg_transaction_core;
/




