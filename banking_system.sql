begin
    if :new.transaction_type_id = pkg_transaction_core.c_deposit then
        update accounts
        set current_balance = nvl(current_balance,0) + :new.amount
        where account_id = :new.to_account_id;
    end if;

    if :new.transaction_type_id = pkg_transaction_core.c_withdraw then
        update accounts
        set current_balance = nvl(current_balance,0) - :new.amount
        where account_id = :new.from_account_id;
    end if;

    if :new.transaction_type_id = pkg_transaction_core.c_transfer then
        update accounts
        set current_balance = nvl(current_balance,0) - :new.amount
        where account_id = :new.from_account_id;

        update accounts
        set current_balance = nvl(current_balance,0) + :new.amount
        where account_id = :new.to_account_id;
    end if;
end;
