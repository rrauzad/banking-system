-------- 3rd page: just loan simulator, calculates monthly payment for loan  with specific % rate + displays total payment:
DECLARE
    v_amount         NUMBER := NVL(:P4_LOAN_AMOUNT, 0);
    v_annual_rate    NUMBER := NVL(:P4_ANNUAL_RATE, 0);  -- percent
    v_term_months    NUMBER := NVL(:P4_TERM_MONTHS, 0);
    v_monthly_rate   NUMBER;
    v_payment        NUMBER;
    v_total_payable  NUMBER;
    v_total_interest NUMBER;
BEGIN
    -- validate 
    IF v_amount <= 0 OR v_term_months <= 0 THEN
        :P4_MONTHLY_PAYMENT := NULL;
        :P4_TOTAL_INTEREST  := NULL;
        :P4_TOTAL_PAYABLE   := NULL;
        RETURN;
    END IF;

    ----convert % to monthly decimal
    v_monthly_rate := v_annual_rate / 12 / 100;

    ----- 0% interest = just division
    IF v_monthly_rate = 0 THEN
        v_payment := v_amount / v_term_months;

    ELSE
        -- standard annuity formula
        v_payment :=
            v_amount * v_monthly_rate /
            (1 - POWER(1 + v_monthly_rate, -v_term_months));
    END IF;

    v_total_payable  := v_payment * v_term_months;
    v_total_interest := v_total_payable - v_amount;

    :P4_MONTHLY_PAYMENT := ROUND(v_payment, 2);
    :P4_TOTAL_PAYABLE   := ROUND(v_total_payable, 2);
    :P4_TOTAL_INTEREST  := ROUND(v_total_interest, 2);
END;




