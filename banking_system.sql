create or replace procedure pr_auto_freeze_fraudulent(p_cust number) is
    v_cnt number;
begin
    select count(*)
    into v_cnt
    from transactions t
    join accounts a on a.account_id = t.from_account_id
    where a.customer_id = p_cust
      and t.is_fraudulent = '1'
      and t.transaction_date >= systimestamp - 1;

    if v_cnt >= 3 then
        update customers
        set status = 'Frozen'
        where customer_id = p_cust;
    end if;

exception
    when others then
        raise_application_error(-31001, 'error during fraud auto-freeze');
end;
